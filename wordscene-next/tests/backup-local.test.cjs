const assert=require('node:assert/strict');
const S=require('../state-guard.js');
globalThis.WordSceneState=S;
const B=require('../backup-local.js');
const original={version:5,words:{mug:{started:true,trained:true,attempts:3,errors:1}},reviewCycle:[],session:null};
const json=B.exportState(original,500,Date.parse('2026-11-01T10:00:00Z'));
const saved=JSON.parse(json);
assert.equal(saved.format,'wordscene-next-local');
assert.equal(saved.version,1);
assert.equal(saved.wordCount,500);
assert.deepEqual(B.importState(json,500),original,'state must round-trip without changes');
assert.notEqual(B.importState(json,500),original,'must restore an independent object');
assert.throws(()=>B.importState('{broken',500),/invalid-json/);
assert.throws(()=>B.importState('x'.repeat(B.MAX_FILE_BYTES+1),500),/file-too-large/);
assert.throws(()=>B.importState(JSON.stringify({...saved,format:'wordscene-original'}),500),/wrong-app-or-version/);
assert.throws(()=>B.importState(JSON.stringify({...saved,version:9}),500),/wrong-app-or-version/);
assert.throws(()=>B.importState(JSON.stringify({...saved,wordCount:499}),500),/wrong-app-or-version/);
assert.throws(()=>B.importState(JSON.stringify({...saved,state:{version:5,words:null}}),500),/invalid-local-state/);
assert.throws(()=>B.importState(JSON.stringify({...saved,state:{version:4,words:{}}}),500),/invalid-local-state/);
console.log('PASS: adult backups are app-specific, validated and reversible.');
