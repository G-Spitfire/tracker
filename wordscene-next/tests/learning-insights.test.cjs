const assert=require('node:assert/strict');
const I=require('../learning-insights.js');
const at=d=>new Date(d+'T12:00:00').getTime();
const day='2026-10-31',now=at(day);
const records=Array.from({length:30},()=>({started:true,trained:true,schedule:{stage:'daily',firstLearnedAt:at('2026-10-01'),checks:[]}}));
assert.equal(I.canLearnNew(records,80,now),false,'backlog requires a daily portion');
for(let i=0;i<15;i++)records[i].schedule.checks.push({id:'r'+i,day,at:now+i,clean:i<13,directions:{0:i<13,1:i<13}});
assert.equal(I.stats(records,now).reviewedToday,15);
assert.equal(I.canLearnNew(records,65,now),true,'one daily portion unlocks up to five new words');
assert.equal(I.stats(records,now).accuracy7,87);
for(let i=15;i<20;i++)records[i].schedule.firstLearnedAt=now;
assert.equal(I.canLearnNew(records,65,now),false,'new words capped while backlog remains');
assert.equal(I.canLearnNew(records,0,now),true,'without backlog children may continue');
assert.equal(I.stats(records,now).week.at(-1).count,15);
assert.equal(I.stats(records,now).reviewedThisWeek,15);
assert.equal(I.speedFeedback([{time:45,errors:2,valid:true},{time:35,errors:0,valid:true}]).kind,'faster');
assert.equal(I.speedFeedback([{time:45,errors:2,valid:true},{time:35,errors:1,valid:true},{time:34,errors:1,valid:true}]).pauseSuggested,true);
assert.equal(I.speedFeedback([{time:45,errors:0,valid:false},{time:35,errors:0,valid:true}]).kind,'unknown','invalid interrupted timing should be excluded');
assert.equal(I.speedFeedback([{time:20,errors:0,valid:true},{time:12,errors:2,valid:true}]).kind,'mixed','speed at the expense of mistakes is not rewarded');
const dates=I.stats(records,now).week;
assert.equal(dates[0].day,'2026-10-25');assert.equal(dates[6].day,day);
console.log('PASS: separate child analytics, daily review gate, backlog cap, speed and interruption checks.');
