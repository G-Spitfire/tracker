const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
const sources=[...html.matchAll(/<script src="\.\/([^"]+)"><\/script>/g)].map(m=>m[1]);
assert.ok(sources.includes('backup-local.js')&&sources.includes('learning-insights.js'));
assert.ok(sources.indexOf('learning-insights.js')<sources.indexOf('backup-local.js'));
assert.ok(html.includes("const KEY='word-scenes-next-lab-v1'"));
assert.ok(!html.includes("localStorage.getItem('word-scenes-v5')"),'no reading original child progress');
assert.ok(html.includes("downloadProgressCopy()")&&html.includes("restoreProgressCopy(this)"));
assert.ok(html.includes('I.pairedCards(s.ids,shuffled)'),'new and review batches must check both directions');
assert.ok(html.includes('I.portion(due,excluded)'),'review batches must be limited and exclude completed words');
assert.ok(html.includes("btn('Учить новые · '+fresh.length"),'new words remain directly available');
assert.ok(html.includes('startOptionalWriting()'),'writing practice is optional');
assert.ok(html.includes('bindRecallSwipe()')&&html.includes("dy< -55")&&html.includes('if(!origin||origin.id!==e.pointerId||s.revealed)return'),'vertical swipe reveals a card without advancing it');
assert.ok(!html.includes('roundRecommendation')&&!html.includes('nextDirection('),'speed rounds must not gate progression');
assert.ok(!html.includes('DAILY_REVIEW_PORTION')&&!html.includes('NEW_WHILE_BACKLOG'),'daily caps must not gate learning');
const grade=html.slice(html.indexOf('function grade('),html.indexOf('function advance('));
assert.ok(grade.includes('advance()')&&!grade.includes('controls()'),'an error must not interrupt a card run');
assert.ok(html.includes("s.phase==='writing'){s.phase='result';completePart()}"),'legacy unfinished writing becomes optional after oral completion');
assert.ok(html.includes("s.phase==='round'){s.dir=1-(s.dir||0)"),'legacy round screens resume through the next direction');
assert.ok(html.includes('st.newToday'),'new words should be visible to the child');
assert.ok(html.includes('d.active'),'weekly activity must include lessons and reviews');
assert.ok(sw.includes("'./backup-local.js'"),'manual backup must work offline');
assert.ok(sw.includes('wsnext-lab-v3'),'cache must refresh');
assert.equal(manifest.name,'WordScene Next · тестовая версия');
assert.equal(manifest.short_name,'WordScene+');
for(const f of sources)assert.ok(fs.existsSync(path.join(root,f)),f+' must exist');
assert.ok(fs.existsSync(path.join(root,'assets/icon-180.png')));
const js=html.slice(html.lastIndexOf('<script>')+8,html.lastIndexOf('</script>'));
assert.doesNotThrow(()=>new Function(js),'inline JS is syntactically sound');
console.log('PASS: isolation, study UI, offline dependencies and recovery controls.');
