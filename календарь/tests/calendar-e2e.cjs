'use strict';
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const out=path.join(__dirname,'artifacts');fs.mkdirSync(out,{recursive:true});
const URL='http://127.0.0.1:8765/календарь/index.html';
const DATE='2026-12-09';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({acceptDownloads:true,viewport:{width:1280,height:800}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const report={};
 try{
  await page.goto(URL);
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent!=='Загрузка…');
  await page.locator('#side-new').click();
  await page.locator('[data-kind="event"]').click();
  await page.locator('#event-name').fill('Аудит — встреча');
  await page.locator('#event-date').fill(DATE);
  await page.locator('#event-start').fill('10:00');
  await page.locator('#event-end').fill('11:00');
  const classes=page.locator('#event-classes input[type="checkbox"]');
  assert.ok(await classes.count()>0,'No classes available');
  await classes.first().check();
  await page.locator('#event-form button[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent==='Событие сохранено');
  const getEvents=()=>page.evaluate(async()=>{const db=await new Promise((ok,no)=>{const q=indexedDB.open('school-calendar-mvp');q.onsuccess=()=>ok(q.result);q.onerror=()=>no(q.error)});const data=await new Promise((ok,no)=>{const q=db.transaction('events').objectStore('events').getAll();q.onsuccess=()=>ok(q.result);q.onerror=()=>no(q.error)});db.close();return data});
  let events=await getEvents();const saved=events.find(e=>e.name==='Аудит — встреча');
  assert.ok(saved,'Event not persisted');assert.equal(saved.date,DATE);report.create=true;
  await page.reload();await page.waitForFunction(()=>document.querySelector('#status')?.textContent!=='Загрузка…');
  events=await getEvents();assert.ok(events.some(e=>e.id===saved.id),'Event lost after reload');report.persistence=true;
  await page.locator('#side-new').click();
  await page.locator('[data-kind="event"]').click();
  await page.locator('#event-name').fill('Ошибка времени');
  await page.locator('#event-date').fill(DATE);
  await page.locator('#event-start').fill('12:00');
  await page.locator('#event-end').fill('11:00');
  await page.locator('#event-classes input[type="checkbox"]').first().check();
  await page.locator('#event-form button[type="submit"]').click();
  assert.match(await page.locator('#event-error').innerText(),/позже начала/);
  assert.equal((await getEvents()).length,events.length,'Invalid event was persisted');
  report.invalidTimeRejected=true;
  await page.locator('#cancel').click();
  await page.locator('#data-nav').click();
  const backupPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const backup=await backupPromise;
  assert.match(backup.suggestedFilename(),/calendar-backup.*\.json/);
  const file=path.join(out,'audit-backup.json');await backup.saveAs(file);
  const json=JSON.parse(fs.readFileSync(file,'utf8'));
  assert.equal(json.version,3);assert.ok(json.data.events.some(e=>e.id===saved.id));
  report.backup=true;
  await page.locator('#settings-back').click();
  const pngPromise=page.waitForEvent('download');
  await page.locator('#side-png').click();
  const png=await pngPromise;
  assert.match(png.suggestedFilename(),/\.png$/);
  const pngPath=path.join(out,'audit-calendar.png');await png.saveAs(pngPath);
  const header=fs.readFileSync(pngPath).subarray(0,8).toString('hex');
  assert.equal(header,'89504e470d0a1a0a','Invalid PNG signature');report.png=true;
  assert.deepEqual(errors,[]);report.pageErrors=errors;
 }catch(e){report.failure=e.stack||String(e);throw e}
 finally{fs.writeFileSync(path.join(out,'e2e-report.json'),JSON.stringify(report,null,2));await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
